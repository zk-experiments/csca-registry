//! Generates `noir/csca_registry/src/vectors.nr` from the committed fixtures and
//! fails if the checked-in file differs, so the Noir library is always tested
//! against what this crate produces. Regenerate with:
//!
//! ```sh
//! UPDATE_NOIR_VECTORS=1 cargo test --test noir_vectors
//! ```

use csca_registry::commands::prove::{prove_key, prove_not_revoked, ProofJson};
use csca_registry::commitment;
use csca_registry::output::{Key, Registry};
use csca_registry::registry::Builder;
use std::fmt::Write;
use std::path::PathBuf;

fn registry() -> Registry {
    let mut b = Builder::default();
    b.add_path(&PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/sources"))
        .unwrap();
    b.finish().unwrap()
}

fn bytes(hex_str: &str) -> String {
    let b = hex::decode(hex_str).unwrap();
    format!(
        "[{}]",
        b.iter()
            .map(|x| format!("0x{x:02x}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn serial20(serial_hex: &str) -> String {
    let b = hex::decode(serial_hex).unwrap();
    let mut out = vec![0u8; 20 - b.len()];
    out.extend(b);
    format!(
        "[{}]",
        out.iter()
            .map(|x| format!("0x{x:02x}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn path(p: &ProofJson) -> String {
    format!(
        "MerklePath {{ index: {}, siblings: [{}] }}",
        p.index,
        p.siblings.join(", ")
    )
}

fn key_fns(out: &mut String, name: &str, reg: &Registry, k: &Key) {
    let p = &k.periods[0];
    let at = p.open + (p.close - p.open) / 2;
    let proof = prove_key(reg, &k.id, at).unwrap();
    let c = k.country_code.as_bytes();
    let n = k.public_key.len() / 2;
    writeln!(out, "// {} {} key {}", k.country, k.description, k.id).unwrap();
    writeln!(
        out,
        "pub(crate) global {name}_KEY: [u8; {n}] = {};",
        bytes(&k.public_key)
    )
    .unwrap();
    writeln!(
        out,
        "pub(crate) global {name}_KEY_HASH: Field = {};",
        k.key_hash
    )
    .unwrap();
    writeln!(out, "pub(crate) global {name}_LEAF: Field = {};", p.leaf).unwrap();
    writeln!(out, "pub(crate) global {name}_AT: u64 = {at};").unwrap();
    writeln!(
        out,
        "pub(crate) fn {}_header() -> KeyHeader {{\n    KeyHeader {{ country: [{}, {}, {}], key_type: {}, curve: {}, bits: {}, exponent: {}, open: {}, close: {} }}\n}}",
        name.to_lowercase(), c[0], c[1], c[2], k.key_type, k.curve, k.bits, k.exponent, p.open, p.close
    )
    .unwrap();
    writeln!(
        out,
        "pub(crate) fn {}_path() -> MerklePath<16> {{\n    {}\n}}\n",
        name.to_lowercase(),
        path(&proof.proof)
    )
    .unwrap();
}

fn generate() -> String {
    let reg = registry();
    let mut out = String::from(
        "// Generated by csca-registry tests/noir_vectors.rs from tests/fixtures/sources. Do not edit.\n\nuse crate::{Exclusion, KeyHeader, MerklePath};\n\n",
    );
    writeln!(
        out,
        "pub(crate) global ROOT: Field = {};",
        reg.commitment.root
    )
    .unwrap();
    writeln!(
        out,
        "pub(crate) global KEYS_ROOT: Field = {};",
        reg.commitment.keys_root
    )
    .unwrap();
    writeln!(
        out,
        "pub(crate) global REVOCATIONS_ROOT: Field = {};\n",
        reg.commitment.revocations_root
    )
    .unwrap();

    let pick = |cc: &str, desc: &str| {
        reg.keys
            .iter()
            .rev()
            .find(|k| k.country == cc && k.description == desc)
            .unwrap()
            .clone()
    };
    key_fns(&mut out, "DE", &reg, &pick("DE", "EC-brainpoolP512r1"));
    key_fns(&mut out, "IT", &reg, &pick("IT", "RSA-4096"));

    // Revocations: one revoked serial, and exclusion witnesses for serials that
    // sort before, between and after the committed leaves.
    let rev = &reg.revocations[0];
    let issuer = reg.keys.iter().find(|k| k.id == rev.issuer_key).unwrap();
    writeln!(
        out,
        "pub(crate) global REV_ISSUER_KEY_HASH: Field = {};",
        issuer.key_hash
    )
    .unwrap();
    writeln!(
        out,
        "pub(crate) global REVOKED_SERIAL: [u8; 20] = {};\n",
        serial20(&rev.serial)
    )
    .unwrap();
    let leaves = reg.revocations.len();
    let mut cases = [None, None, None];
    for s in 1u32..10_000 {
        let serial = format!("{s:06x}");
        let Ok(p) = prove_not_revoked(&reg, &issuer.id, &serial) else {
            continue;
        };
        let slot = match (&p.lower, p.upper.index) {
            (None, _) => 0,
            (Some(_), i) if i == leaves => 2,
            _ => 1,
        };
        if cases[slot].is_none() {
            cases[slot] = Some((serial, p));
        }
        if cases.iter().all(Option::is_some) {
            break;
        }
    }
    for (name, case) in ["BEFORE", "BETWEEN", "AFTER"].iter().zip(cases) {
        let (serial, p) = case.expect("exclusion case");
        let lower = p.lower.as_ref();
        writeln!(
            out,
            "pub(crate) global SERIAL_{name}: [u8; 20] = {};",
            serial20(&serial)
        )
        .unwrap();
        writeln!(
            out,
            "pub(crate) fn exclusion_{}() -> Exclusion<14> {{\n    Exclusion {{\n        has_lower: {},\n        lower_leaf: {},\n        lower: {},\n        upper_leaf: {},\n        upper: {},\n    }}\n}}\n",
            name.to_lowercase(),
            lower.is_some(),
            lower.map_or("0".into(), |l| l.leaf.clone()),
            lower.map_or("MerklePath { index: 0, siblings: [0; 14] }".into(), path),
            p.upper.leaf,
            path(&p.upper),
        )
        .unwrap();
    }
    let _ = commitment::LEAF_VERSION;
    out
}

#[test]
fn noir_vectors_are_current() {
    let file = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("noir/csca_registry/src/vectors.nr");
    let fresh = generate();
    if std::env::var_os("UPDATE_NOIR_VECTORS").is_some() {
        std::fs::write(&file, &fresh).unwrap();
    }
    let current = std::fs::read_to_string(&file).unwrap_or_default();
    assert!(
        current == fresh,
        "noir/csca_registry/src/vectors.nr is stale; run UPDATE_NOIR_VECTORS=1 cargo test --test noir_vectors"
    );
}
